// Bundles the local runtime (NestJS API + engine) into a single CommonJS file for the
// Electron utility process. The input is the tsc output of apps/api, which already contains
// the decorator metadata NestJS needs (esbuild alone cannot emit it).
import { build } from 'esbuild'
import { copyFileSync, existsSync, writeFileSync, cpSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const entry = path.resolve(root, '../api/dist/main.js')
if (!existsSync(entry)) {
  console.error(`Missing ${entry}. Run "pnpm --filter @multi-ai-coder/api build" first.`)
  process.exit(1)
}

await build({
  entryPoints: [entry],
  outfile: path.join(root, 'dist/backend/main.cjs'),
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node22',
  sourcemap: true,
  logLevel: 'warning',
  // import.meta.url is only used as a dev fallback for locating migrations.
  define: { 'import.meta.url': '__mac_import_meta_url' },
  banner: { js: "const __mac_import_meta_url = require('url').pathToFileURL(__filename).href;" },
  external: [
    '@prisma/client',
    '.prisma/client',
    // optional NestJS integrations that are not used
    '@nestjs/microservices',
    '@nestjs/microservices/*',
    '@nestjs/websockets',
    '@nestjs/websockets/*',
    'class-validator',
    'class-transformer',
    'class-transformer/storage',
    '@fastify/static',
    '@nestjs/platform-socket.io',
  ],
})
console.log('backend bundle → dist/backend/main.cjs')

// Plugin host (one process per plugin, started by the runtime): a dependency-free CommonJS file.
const pluginHost = path.resolve(root, '../api/dist/plugins/host/plugin-host.cjs')
if (!existsSync(pluginHost)) {
  console.error(`Missing ${pluginHost}. Run "pnpm --filter @multi-ai-coder/api build" first.`)
  process.exit(1)
}
copyFileSync(pluginHost, path.join(root, 'dist/backend/plugin-host.cjs'))
console.log('plugin host → dist/backend/plugin-host.cjs')

// TypeScript language-service worker (runs in a worker thread of the runtime).
await build({
  entryPoints: [path.resolve(root, '../api/dist/ide/ts-worker.js')],
  outfile: path.join(root, 'dist/backend/ts-worker.cjs'),
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node22',
  logLevel: 'warning',
  define: { 'import.meta.url': '__mac_import_meta_url' },
  banner: { js: "const __mac_import_meta_url = require('url').pathToFileURL(__filename).href;" },
  external: ['@prisma/client', '.prisma/client'],
})
console.log('typescript worker → dist/backend/ts-worker.cjs')
const apiRequire = createRequire(path.resolve(root, '../api/package.json'))
copyFileSync(apiRequire.resolve('typescript-language-server/lib/cli.mjs'), path.join(root, 'dist/backend/lsp-server.mjs'))
cpSync(path.dirname(apiRequire.resolve('typescript/package.json')), path.join(root, 'dist/backend/typescript'), { recursive: true })

// Boot files: enable V8's on-disk compile cache (in the user's data folder) before the large bundles
// are compiled; from the second start on, compiling main.cjs is mostly skipped.
const boot = (target) => `// Generated by build-backend.mjs: V8 compile cache, then the bundle.
const path = require('node:path')
try {
  require('node:module').enableCompileCache?.(path.join(process.env.MAC_DATA_DIR || require('node:os').tmpdir(), 'cache', 'v8'))
} catch {
  // compile cache unavailable: start without it
}
require('./${target}')
`
writeFileSync(path.join(root, 'dist/backend/boot.cjs'), boot('main.cjs'))
writeFileSync(path.join(root, 'dist/backend/ts-worker-boot.cjs'), boot('ts-worker.cjs'))
console.log('boot files → dist/backend/boot.cjs, ts-worker-boot.cjs')
